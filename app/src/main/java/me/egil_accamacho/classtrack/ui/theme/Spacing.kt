package me.egil_accamacho.classtrack.ui.theme

import androidx.compose.ui.unit.dp

/**
 * ClassTrack spacing scale — Manual de Marca §12.
 * 8dp-grid system using multiples of 4.
 *
 * Usage: `Modifier.padding(CtSpacing.base)` → 16.dp
 */
object CtSpacing {
    val xs    = 4.dp
    val sm    = 8.dp
    val md    = 12.dp
    val base  = 16.dp
    val lg    = 24.dp
    val xl    = 32.dp
    val xxl   = 48.dp
    val xxxl  = 64.dp
}
